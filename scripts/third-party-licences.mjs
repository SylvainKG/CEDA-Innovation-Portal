#!/usr/bin/env node
// Lists every third-party package and its licence (backlog REL-01: "the source lists third
// party licences"). Reads the committed lockfiles only, so it needs no network and no install.
//
// Usage (Node 20+, no dependencies):
//   node scripts/third-party-licences.mjs            # writes THIRD_PARTY_LICENCES.md
//   node scripts/third-party-licences.mjs --check    # exits 1 if the file is out of date or a licence needs a decision
//
// Runtime packages are the ones that ship in the built site (not marked "dev" in the lockfile).
// Everything else is build, test or lint tooling and never reaches users.
// A licence outside the ALLOWED list stops the check, so a new copyleft or unknown licence is a
// team decision rather than a surprise in the submitted source.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT = path.join(root, 'THIRD_PARTY_LICENCES.md')
const LOCKFILES = [
  { file: 'package-lock.json', label: 'Portal (frontend, build and test tooling)' },
  { file: 'tools/pglite-db-tests/package-lock.json', label: 'Database test tools (`tools/pglite-db-tests`, never deployed)' },
]

// Permissive licences, plus those reviewed and accepted for this project:
// MPL-2.0 (file-level copyleft; used unmodified), CC-BY-4.0 (data, attribution kept here),
// OFL-1.1 (font licence), Python-2.0 (permissive). Anything else needs a decision before release.
const ALLOWED = new Set([
  'MIT', 'MIT-0', 'ISC', 'Apache-2.0', 'BSD-2-Clause', 'BSD-3-Clause', '0BSD', 'BlueOak-1.0.0', 'CC0-1.0',
  'Unlicense', 'MPL-2.0', 'CC-BY-4.0', 'OFL-1.1', 'Python-2.0',
])

function packagesOf(lockPath) {
  const lock = JSON.parse(fs.readFileSync(lockPath, 'utf8'))
  if (lock.lockfileVersion < 2) throw new Error(`${lockPath}: lockfileVersion ${lock.lockfileVersion} has no per-package licence field`)
  const out = []
  for (const [key, meta] of Object.entries(lock.packages)) {
    if (!key) continue // the project itself
    const name = meta.name ?? key.slice(key.lastIndexOf('node_modules/') + 'node_modules/'.length)
    out.push({ name, version: meta.version ?? '', licence: String(meta.license ?? 'UNKNOWN'), runtime: !meta.dev })
  }
  // One row per name@version (the same package can sit at several paths).
  const seen = new Map()
  for (const p of out) {
    const id = `${p.name}@${p.version}`
    const prev = seen.get(id)
    seen.set(id, prev ? { ...prev, runtime: prev.runtime || p.runtime } : p)
  }
  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))
}

function licenceParts(licence) {
  // SPDX expressions: with OR (e.g. "(MIT OR Apache-2.0)") one allowed option is enough, because we
  // may choose it; with AND, or a single id, every id must be allowed.
  const ids = licence.replace(/[()]/g, ' ').split(/\s+(?:OR|AND)\s+|\s+/).filter(Boolean)
  const isOr = /\sOR\s/.test(licence)
  return isOr ? ids.some((id) => ALLOWED.has(id)) : ids.every((id) => ALLOWED.has(id))
}

const sections = []
const problems = []
for (const { file, label } of LOCKFILES) {
  const p = path.join(root, file)
  if (!fs.existsSync(p)) continue
  const pkgs = packagesOf(p)
  for (const pkg of pkgs) if (!licenceParts(pkg.licence)) problems.push(`${file}: ${pkg.name}@${pkg.version} has licence "${pkg.licence}"`)
  const counts = {}
  for (const pkg of pkgs) counts[pkg.licence] = (counts[pkg.licence] ?? 0) + 1
  const summary = Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([l, n]) => `${l} ${n}`).join(' · ')
  const table = (rows) => ['| Package | Version | Licence |', '|---|---|---|', ...rows.map((r) => `| \`${r.name}\` | ${r.version} | ${r.licence} |`)].join('\n')
  const runtime = pkgs.filter((x) => x.runtime)
  const tooling = pkgs.filter((x) => !x.runtime)
  sections.push([
    `## ${label}`,
    '',
    `Source: \`${file}\`. ${pkgs.length} packages: ${summary}.`,
    '',
    ...(runtime.length && file === 'package-lock.json'
      ? [`### Ships in the built site (${runtime.length})`, '', table(runtime), '', `### Build, test and lint tooling only (${tooling.length})`, '', table(tooling)]
      : [table(pkgs)]),
    '',
  ].join('\n'))
}

const doc = [
  '# Third-party licences',
  '',
  'Generated by `node scripts/third-party-licences.mjs` from the committed lockfiles. Do not edit by hand:',
  'run the script again after any dependency change (`--check` fails when this file is out of date).',
  '',
  'Not listed here, because they are not npm packages:',
  '- the CEDA name and logo, which belong to CEDA and are not covered by an open-source licence;',
  '- hosted services used at run time (Supabase, AWS Amplify), which are covered by their own terms of service.',
  '',
  ...sections,
].join('\n')

const check = process.argv.includes('--check')
if (check) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''
  if (current !== doc) problems.push('THIRD_PARTY_LICENCES.md is out of date: run node scripts/third-party-licences.mjs')
} else {
  fs.writeFileSync(OUT, doc)
  console.log(`wrote ${path.relative(root, OUT)}`)
}
if (problems.length) {
  for (const p of problems) console.error(`third-party-licences: ${p}`)
  process.exit(1)
}
if (check) console.log('third-party-licences: up to date, every licence allowed')
